def all_features():
    """展开为统一记录列表。"""
    out = []
    for key, rows in [("天枢", PB), ("天璇", OP), ("天玑", CF), ("天权", MA),
                      ("玉衡", IX), ("开阳", EN), ("瑶光", RC)]:
        code = ARRAYS[key]["code"]
        for r in rows:
            (fid, layer, name, desc, criteria, evt, dvt, pvt, std, ev, prio) = r
            out.append({
                "id": fid, "array": key, "array_full": ARRAYS[key]["full"],
                "array_code": code, "layer": layer, "name": name, "desc": desc,
                "criteria": criteria,
                "evt": evt, "dvt": dvt, "pvt": pvt,
                "std": std, "evidence": ev, "priority": prio,
                # 阶段计数便于汇总
                "n_stage": sum(1 for x in (evt, dvt, pvt) if x and x.strip() not in ("—", "")),
            })
    return out


