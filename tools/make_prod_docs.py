ACCENT = RGBColor(0x0E, 0x6B, 0x8A)
GREY = RGBColor(0x5A, 0x6A, 0x7A)


def _font(run, size=10.5, bold=False, color=None):
    run.font.name = CN
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rf)
    rf.set(qn("w:eastAsia"), CN)


def doc_new(title, subtitle, meta):
    d = Document()
    st = d.styles["Normal"]
    st.font.name = CN
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    for s in d.sections:
        s.top_margin = Cm(2.2)
        s.bottom_margin = Cm(2.0)
        s.left_margin = Cm(2.4)
        s.right_margin = Cm(2.0)
    p = d.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(120)
    _font(p.add_run(title), 26, True, ACCENT)
    p2 = d.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _font(p2.add_run(subtitle), 13, False, GREY)
    for line in meta:
        p3 = d.add_paragraph()
        p3.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _font(p3.add_run(line), 10, False, GREY)
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    return d


def h1(d, text):
    p = d.add_heading(level=1)
    _font(p.add_run(text), 16, True, ACCENT)
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after = Pt(8)


def h2(d, text):
    p = d.add_heading(level=2)
    _font(p.add_run(text), 12.5, True, RGBColor(0x1A, 0x1A, 0x1A))
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)


def para(d, text, size=10.5, bold=False, indent=True, color=None):
    p = d.add_paragraph()
    p.paragraph_format.space_after = Pt(5)
    p.paragraph_format.line_spacing = 1.35
    if indent:
        p.paragraph_format.first_line_indent = Pt(21)
    _font(p.add_run(text), size, bold, color)
    return p


def bullets(d, items, size=10.5):
    for it in items:
        p = d.add_paragraph()
        p.paragraph_format.left_indent = Pt(16)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.3
        if isinstance(it, tuple):
            _font(p.add_run("• "), size, True, ACCENT)
            _font(p.add_run(it[0] + "："), size, True)
            _font(p.add_run(it[1]), size)
        else:
            _font(p.add_run("• " + it), size)


def table(d, headers, rows, widths=None, size=9.5, note=""):
    t = d.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        _font(p.add_run(h), size, True)
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            _font(p.add_run(str(v)), size)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    if note:
        p = d.add_paragraph()
        p.paragraph_format.space_before = Pt(3)
        _font(p.add_run(note), 9, False, GREY)
    d.add_paragraph().paragraph_format.space_after = Pt(2)


